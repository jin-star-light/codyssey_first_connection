SEASONAL_FRUITS: dict[int, tuple[Fruit, ...]] = {
    month: tuple(_FRUITS[name] for name in names)
    for month, names in _MONTHLY_NAMES.items()
}


def get_monthly_fruits(month: int) -> list[Fruit]:
    """월에 해당하는 추천 후보 3종을 복사해 반환한다."""
    if month not in SEASONAL_FRUITS:
        raise ValueError("month must be between 1 and 12")
    return [dict(fruit) for fruit in SEASONAL_FRUITS[month][:3]]
